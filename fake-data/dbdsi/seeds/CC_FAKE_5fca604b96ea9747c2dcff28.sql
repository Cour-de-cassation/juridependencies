 DU 23 OCTOBRE 2024
 
 
 
 *DEBAR M. Philippe Dominique a formé un pourvoi contre l''arrêt de la chambre de l''instruction de la cour d''appel de Rennes, en date du 20 octobre 2023, qui l''a déclaré pénalement irresponsable des faits de violences et rébellion, aggravées, a prononcé sur une admission en soins psychiatriques sous la forme d''une hospitalisation complète ainsi que sur des mesures de sûreté. *FINAR 
 
 *DEBUT Un mémoire a été produit.
 
 Sur le rapport de Mme Leprieur, conseiller, les observations de la SCP Boucard-Maman, avocat de M. Philippe Dominique, et les conclusions de M. Stark, avocat général, après débats en l''audience publique du 25 septembre 2024 où étaient présents M. Lannister, président, Mme Leprieur, conseiller rapporteur, M. de Larosière de Champfeu, conseiller de la chambre, et Mme Sommier, greffier de chambre,
 
 la chambre criminelle de la Cour de cassation, composée en application de l''article 567-1-1 du c') || TO_CLOB('ode de procédure pénale, des président et conseillers précités, après en avoir délibéré conformément à la loi, a rendu le présent arrêt.*FIN 
 
 *DEBDAR Faits et procédure
 
 1. Il résulte de l''arrêt attaqué et des pièces de la procédure ce qui suit.
 
 2. Le 16 février 2022, M. Philippe Dominique a tiré au moyen d''un fusil de chasse sur le tracteur conduit par son voisin, M. Jean Antoinette ; huit traces d''impact ont été relevées sur la carrosserie.
 
 3. Lors de l''intervention des gendarmes, le 1er mars 2022, M. Dominique a mis en joue ceux-ci avec une carabine et résisté violemment à son interpellation. Plusieurs armes et munitions ont été découvertes à son domicile.
 
 4. M. Dominique a été mis en examen pour violences avec arme et préméditation ainsi que rébellion avec arme.
 
 5. Par ordonnance du 17 juillet 2023, le juge d''instruction a retenu qu''il existait à son encontre, d''une part, des charges suffisantes et, d''autre part, des raisons plausibles de considérer qu''il') || TO_CLOB(' était atteint, au moment des faits, d''un trouble psychique ou neuro-psychique ayant aboli son discernement ou le contrôle de ses actes. Il a ordonné la transmission de la procédure au procureur général pour saisine de la chambre de l''instruction.
 
 Examen des moyens 
 
 Sur le premier moyen 
 
 6. Il n''est pas de nature à permettre l''admission du pourvoi au sens de l''article 567-1-1 du code de procédure pénale.
 
 Sur le second moyen
 
 Enoncé du moyen
 
 7. Le moyen critique l''arrêt attaqué en ce qu''il a dit qu''il existe des charges suffisantes contre M. Dominique d''avoir volontairement exercé des violences aggravées sur M. Antoinette et d''avoir opposé une résistance violente aux gendarmes matriculés [Numéro identifiant 2], [Numéro identifiant 3] et [Numéro identifiant 1], l''a déclaré irresponsable pénalement de ces faits et, d''une part, a ordonné son admission en soins psychiatriques sous la forme d''une hospitalisation complète dans un établissement mentionné à l''art') || TO_CLOB('icle L. 3222-1 du code de la santé publique, d''autre part, a prononcé les mesures de sûreté suivantes à son encontre : 
1°) interdiction d''entrer en relation avec la victime de l''infraction, M. Antoinette, son épouse et ses enfants, pour une durée de dix ans ; 
2°) interdiction de paraître sur les communes de Aubry et de Clément-les-Bains pour une durée de dix ans ; 
3°) interdiction de paraître sur les communes de Seguin pour une durée de cinq ans ; 
4°) interdiction de détenir une arme pour une durée de dix ans, alors :
 
 « 1°/ que toute ingérence dans l''exercice du droit à la vie privée et familiale, qui recouvre la protection du domicile, doit être prévue par la loi, justifiée par un but légitime et proportionnée au but poursuivi ; que l''interdiction de paraître dans tout lieu spécialement désigné, qui peut être prononcée à titre de mesure de sûreté par la chambre de l''instruction contre une personne déclarée irresponsable pénalement pour cause de trouble mental, ne saurait') || TO_CLOB(' concerner tout le territoire d''une commune où l''intéressé a son domicile, dès lors qu''une telle ingérence dans la vie privée et familiale n''est pas expressément prévue par la loi ; qu''en faisant interdiction à M. Dominique, pendant une durée de cinq ans, de paraître dans la commune de Seguin, où il est domicilié avec son épouse et l''un de ses fils, au motif que cette interdiction permettrait d''éviter toute rencontre fortuite avec ses voisins et les services de police victimes des faits qui lui ont été reprochés, que ses enfants ne sont plus à charge et qu''il peut continuer à exercer ses droits familiaux autrement en étant hébergé chez une de ses filles qui habite dans une autre ville, la chambre de l''instruction a méconnu l''article 706-136 du code de procédure pénale ensemble l''article 8 de la Convention européenne de droits de l''homme ;
 
 2°/ qu''en toute hypothèse, l''interdiction de paraître dans tout lieu spécialement désigné, qui peut être prononcée à titre de mesur') || TO_CLOB('e de sûreté par la chambre de l''instruction contre une personne déclarée irresponsable pénalement pour cause de trouble mental, ne saurait porter une atteinte disproportionnée à la vie privée et familiale de l''intéressé, ce dont le juge du fond, saisi d''un tel moyen, doit s''assurer par une motivation in concreto ; qu''en retenant, pour prononcer contre M. Dominique une interdiction de paraître pendant cinq ans dans la commune de Seguin, où il est domicilié avec son épouse et l''un de ses fils, que cette interdiction permettrait d''éviter toute rencontre fortuite avec ses voisins et les services de police victimes des faits qui lui ont été reprochés, que ses enfants ne sont plus à charge et qu''il peut continuer à exercer ses droits familiaux autrement en étant hébergé chez une de ses filles qui habite dans une autre ville, la chambre de l''instruction a statué par des motifs impropres à caractériser l''absence d''atteinte disproportionnée à la vie privée et familiale de M. Dominiq') || TO_CLOB('ue, au regard notamment de son âge, de sa situation professionnelle et de la capacité pour sa fille de l''accueillir à son domicile pour faire respecter cette interdiction ; qu''elle n''a par conséquent pas justifié sa décision au regard des articles 706-136 et 593 du code de procédure pénale, ensemble l''article 8 de la Convention européenne de droits de l''homme. »
 
 Réponse de la Cour
 
 8. Pour prononcer à l''encontre du demandeur l''interdiction de paraître sur la commune de Campénéac pour une durée de cinq ans, l''arrêt attaqué relève que ladite commune constitue le lieu des faits, celui du domicile de la victime et de sa famille ainsi que de M. Dominique, de son épouse à la retraite et de son fils.
 
 9. Les juges énoncent que l''interdiction de paraître sur cette commune, requise par le ministère public, constitue une atteinte à la vie privée et familiale de M. Dominique.
 
 10. Ils retiennent que cette interdiction poursuit néanmoins un but légitime. En effet, compte tenu du') || TO_CLOB(' litige opposant M. Dominique à M. Antoinette, l''interdiction d''entrer en relation avec la victime n''est pas suffisante en ce que les deux parties pourraient se retrouver fortuitement sur la commune de Seguin et raviver des troubles préjudiciables, ce d''autant que leur conflit remonte à 2013. Ainsi, l''interdiction de paraître évite le risque de renouvellement des faits qui, selon les experts, est qualifié de certain ou de très élevé et elle permet la tranquillité légitime de la victime et de sa famille.
 
 11. Ils ajoutent que M. Dominique n''est nullement privé de contact avec sa famille, alors que ses enfants sont adultes et autonomes. De plus, l''intéressé continue de jouir de ses droits familiaux à charge pour lui de les exercer autrement, comme il l''a proposé et l''a fait dans le cadre de l''information judiciaire, notamment en étant hébergé chez sa fille.
 
 12. Ils concluent que l''interdiction de paraître à Seguin n''est pas disproportionnée.
 
 13. En statuant ainsi, la') || TO_CLOB(' chambre de l''instruction n''a méconnu aucun des textes visés au moyen pour les motifs qui suivent.
 
 14. En premier lieu, selon l''article 706-136 du code de procédure pénale, lorsqu''une juridiction prononce une décision de déclaration d''irresponsabilité pénale pour cause de trouble mental, elle peut ordonner à l''encontre de la personne, pendant une durée qu''elle fixe et qui ne peut excéder dix ans en matière correctionnelle, des mesures de sûreté, notamment l''interdiction de paraître dans tout lieu spécialement désigné.
 
 15. Il se déduit de cette formulation générale que la loi prévoit la possibilité pour la juridiction de prononcer, à l''encontre de la personne déclarée pénalement irresponsable, une interdiction de paraître à son domicile.
 
 16. Cette ingérence dans l''exercice du droit au respect de son domicile ainsi que de sa vie privée et familiale, prévu par l''article 8 de la Convention européenne des droits de l''homme, doit cependant être nécessaire et proportionn') || TO_CLOB('ée, ce qu''il appartient au juge de contrôler lorsque cette garantie est invoquée.
 
 17. En second lieu, la chambre de l''instruction, qui a procédé au contrôle de proportionnalité de la mesure en prenant en considération les circonstances de commission des faits, leur gravité, le risque de réitération et la situation personnelle de l''intéressé, a statué par des motifs exempts d''insuffisance comme de contradiction et justifié sa décision.
 
 18. Dès lors, le moyen doit être écarté.
 
 19. Par ailleurs, l''arrêt est régulier en la forme.
 
